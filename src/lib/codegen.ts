// Stage 3 — Generate: turn a ConnectorSpec into a standalone TypeScript MCP server.
// Deterministic template, so the output always compiles; Claude's judgement lives in the spec.
import type { AppliedPattern } from "./db";
import type { ConnectorSpec, ToolSpec } from "./spec";

/** Tool description shown to the agent: what it does + every tribal rule that applies to it. */
export function toolDescription(spec: ConnectorSpec, tool: ToolSpec): string {
  const rules = spec.rules.filter((r) => tool.ruleIds.includes(r.id));
  if (!rules.length) return tool.description;
  return `${tool.description}\n\nTribal knowledge (enforced by this connector):\n${rules.map((r) => `- ${r.text}`).join("\n")}`;
}

/** Params the agent supplies (the pagination param is driven by the connector itself). */
export function agentParams(tool: ToolSpec) {
  return tool.params.filter((p) => p.name !== tool.pagination?.param);
}

export function slugify(name: string) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "connector";
}

const envPrefix = (name: string) => slugify(name).toUpperCase().replace(/-/g, "_");
const q = (s: string) => JSON.stringify(s);

function zodFor(p: ToolSpec["params"][number]) {
  const base = p.type === "number" ? "z.number()" : p.type === "boolean" ? "z.boolean()" : "z.string()";
  return `${base}${p.required ? "" : ".optional()"}.describe(${q(p.description)})`;
}

function toolBlock(spec: ConnectorSpec, tool: ToolSpec): string {
  const params = agentParams(tool);
  const schema = params.length ? `{\n${params.map((p) => `      ${p.name}: ${zodFor(p)},`).join("\n")}\n    }` : "{}";
  const pick = (where: string) => params.filter((p) => p.in === where).map((p) => q(p.name));

  const body: string[] = [];
  if (tool.blockedHours) {
    body.push(`assertAllowedHour(${tool.blockedHours.startHour}, ${tool.blockedHours.endHour});`);
  }
  for (const p of params.filter((x) => x.normalize)) {
    const fn = p.normalize === "uppercase" ? "toUpperCase()" : p.normalize === "lowercase" ? "toLowerCase()" : "trim()";
    body.push(`if (typeof args.${p.name} === "string") args.${p.name} = args.${p.name}.${fn}; // tribal rule`);
  }
  const opts = [
    `path: fillPath(${q(tool.path)}, args)`,
    pick("query").length ? `query: pick(args, [${pick("query").join(", ")}])` : null,
    pick("body").length ? `body: pick(args, [${pick("body").join(", ")}])` : null,
    tool.silentError ? `silentError: ${JSON.stringify(tool.silentError)}` : null,
  ].filter(Boolean);
  const req = `{ ${opts.join(", ")} }`;
  body.push(
    tool.pagination
      ? `return fetchAllPages(${q(tool.method)}, ${req}, ${JSON.stringify(tool.pagination)});`
      : `return call(${q(tool.method)}, ${req});`,
  );

  return `server.registerTool(
  ${q(tool.name)},
  {
    description: ${q(toolDescription(spec, tool))},
    inputSchema: ${schema},
  },
  (args: Record<string, any>) =>
    respond(async () => {
      ${body.join("\n      ")}
    }),
);`;
}

export function generateServer(spec: ConnectorSpec, applied: AppliedPattern[]): string {
  const env = envPrefix(spec.systemName);
  const a = spec.auth;
  const header = [
    `/**`,
    ` * ${spec.systemName} MCP server — generated by AI Connector`,
    ` * ${spec.summary}`,
    ` *`,
    ` * Run:`,
    ` *   npm i @modelcontextprotocol/sdk zod`,
    ` *   npx tsx ${slugify(spec.systemName)}-mcp-server.ts`,
    ` *`,
    ` * Env: ${env}_BASE_URL${a.tokenEndpoint ? `, ${env}_CREDENTIALS (JSON body for ${a.tokenEndpoint})` : ""}`,
    applied.length ? ` *\n * Learned patterns applied: ${applied.map((p) => p.name).join(", ")}` : null,
    ` *`,
    ` * Tribal rules:`,
    ...spec.rules.map((r) => ` *   - ${r.text}`),
    ` */`,
  ]
    .filter((l) => l !== null)
    .join("\n");

  return `${header}
import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { StdioServerTransport } from "@modelcontextprotocol/sdk/server/stdio.js";
import { z } from "zod";

const BASE_URL = process.env.${env}_BASE_URL ?? ${q(spec.baseUrl)};
const CREDENTIALS = process.env.${env}_CREDENTIALS ?? ${q(a.credentials ?? "{}")};
const AUTH = ${JSON.stringify({ type: a.type, tokenEndpoint: a.tokenEndpoint, tokenField: a.tokenField, headerName: a.headerName, headerPrefix: a.headerPrefix, refreshOn401: a.refreshOn401 })};
const MAX_PAGES = 20;

type SilentError = { field: string; okValues: string[]; messageField: string };
type Pagination = { style: "page" | "cursor"; param: string; itemsField: string; nextField: string };
type RequestOpts = { path: string; query?: Record<string, unknown>; body?: Record<string, unknown>; silentError?: SilentError };

// ---------- auth ----------
let token: string | null = null;

async function login() {
  if (!AUTH.tokenEndpoint) return;
  const res = await fetch(BASE_URL + AUTH.tokenEndpoint, {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: CREDENTIALS,
  });
  const json = await res.json();
  token = json[AUTH.tokenField ?? "token"] ?? null;
  if (!token) throw new Error("Login failed: " + JSON.stringify(json));
}

// ---------- request helpers (tribal-rule handling lives here) ----------
async function call(method: string, opts: RequestOpts, retried = false): Promise<any> {
  if (AUTH.type !== "none" && AUTH.tokenEndpoint && !token) await login();
  const url = new URL(BASE_URL + opts.path);
  for (const [k, v] of Object.entries(opts.query ?? {})) url.searchParams.set(k, String(v));
  const headers: Record<string, string> = { "content-type": "application/json" };
  if (token) headers[AUTH.headerName] = AUTH.headerPrefix + token;

  const res = await fetch(url, { method, headers, body: method === "GET" ? undefined : JSON.stringify(opts.body ?? {}) });
  if (res.status === 401 && AUTH.refreshOn401 && !retried) {
    token = null; // token expired: log in again and retry once
    return call(method, opts, true);
  }
  if (!res.ok) throw new Error(\`HTTP \${res.status}: \${await res.text()}\`);
  const json = await res.json();
  if (opts.silentError) {
    // HTTP 200 does not mean success on this system
    const { field, okValues, messageField } = opts.silentError;
    if (!okValues.includes(String(json[field]))) throw new Error(String(json[messageField] ?? \`\${field}=\${json[field]}\`));
  }
  return json;
}

async function fetchAllPages(method: string, opts: RequestOpts, p: Pagination) {
  const items: unknown[] = [];
  let cursor: string | number = p.style === "page" ? 1 : "";
  for (let i = 0; i < MAX_PAGES; i++) {
    const query = { ...opts.query, ...(p.style === "page" || cursor ? { [p.param]: cursor } : {}) };
    const page = await call(method, { ...opts, query });
    items.push(...(page[p.itemsField] ?? []));
    if (!page[p.nextField]) break;
    cursor = p.style === "page" ? (cursor as number) + 1 : String(page[p.nextField]);
  }
  return { items, count: items.length };
}

function assertAllowedHour(startHour: number, endHour: number) {
  const hour = new Date().getHours();
  if (hour >= startHour && hour < endHour) {
    throw new Error(\`Refused: this action is not allowed between \${startHour}:00 and \${endHour}:00 (local time).\`);
  }
}

function fillPath(path: string, args: Record<string, any>) {
  return path.replace(/[:{](\\w+)}?/g, (_m, name) => encodeURIComponent(String(args[name] ?? "")));
}

function pick(args: Record<string, any>, keys: string[]) {
  return Object.fromEntries(keys.filter((k) => args[k] !== undefined).map((k) => [k, args[k]]));
}

async function respond(fn: () => Promise<unknown>) {
  try {
    return { content: [{ type: "text" as const, text: JSON.stringify(await fn(), null, 2) }] };
  } catch (e) {
    return { isError: true, content: [{ type: "text" as const, text: (e as Error).message }] };
  }
}

// ---------- tools ----------
const server = new McpServer({ name: ${q(slugify(spec.systemName))}, version: "1.0.0" });

${spec.tools.map((t) => toolBlock(spec, t)).join("\n\n")}

await server.connect(new StdioServerTransport());
`;
}
